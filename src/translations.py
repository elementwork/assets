def translate_categories(categories: dict, lang: str = "en") -> dict:
    """Return a copy of the categories dict with translated names if needed."""
    if lang == "en":
        return categories
    mapping = CATEGORY_TRANSLATIONS.get(lang, {})
    translated = {}
    for key, value in categories.items():
        new_key = mapping.get(key, key)
        translated[new_key] = value.copy()
    return translated


def translate_field_definitions(field_defs: dict, lang: str = "en") -> dict:
    """Return a copy of field definitions with translated labels and groups."""
    if lang == "en":
        return field_defs
    mapping = {
        "Core Identity": _("core_identity", lang),
        "Ownership": _("ownership", lang),
        "Institution & Access": _("institution_access", lang),
        "Financial Value": _("financial_value", lang),
        "Dates": _("dates", lang),
        "Registration & Tax": _("registration_tax", lang),
        "Location & Access": _("location_access", lang),
        "Insurance & Protection": _("insurance", lang),
        "Status & Control": _("status_control", lang),
        "Beneficiary Designation": _("beneficiary_designation", lang),
        "Estate Planning": _("estate_planning", lang),
        "Documentation": _("documentation", lang),
        "Notes": _("notes", lang),
        "Notes & Comments": _("notes", lang),
    }
    translated = {}
    for field, meta in field_defs.items():
        new_meta = meta.copy()
        if "group" in new_meta:
            new_meta["group"] = mapping.get(new_meta["group"], new_meta["group"])
        if "label" in new_meta:
            # Look up the Excel column translation key for this field
            col_key = f"col_{field}"
            zh_ui = UI_TRANSLATIONS.get("zh", {})
            if col_key in zh_ui:
                new_meta["label"] = zh_ui[col_key]
        translated[field] = new_meta
    return translated


def translate_assets(assets: list, lang: str = "en") -> list:
    """Return a copy of assets with translated category names."""
    if lang == "en":
        return assets
    mapping = CATEGORY_TRANSLATIONS.get(lang, {})
    translated = []
    for asset in assets:
        new_asset = asset.copy()
        if "category" in new_asset and new_asset["category"] in mapping:
            new_asset["category"] = mapping[new_asset["category"]]
        translated.append(new_asset)
    return translated


